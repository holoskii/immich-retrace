// The demo stub (demo/stub.ts) must answer like Immich for everything the viewer calls: its
// responses are parsed here by the real server/adapter.ts and relayed by server/app.ts.

import {mkdirSync, mkdtempSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {afterAll, describe, expect, it} from 'vitest';
import {createStub, loadManifest, STUB_VERSION} from '../demo/stub.ts';
import {albumMembers} from '../demo/manifest.ts';
import {fetchAlbumMembers, fetchAlbums, fetchManifestMonths, fetchMonthColumns, UUID} from '../server/adapter.ts';
import {createApp} from '../server/app.ts';
import {HttpError, ImmichClient} from '../server/immich.ts';

const manifest = loadManifest();
const photo = manifest.assets.find(a => a.kind === 'photo')!;
const video = manifest.assets.find(a => a.kind === 'video')!;
const mine = manifest.assets.filter(a => a.owner === 'me');
const friends = manifest.assets.filter(a => a.owner === 'friend');
const sharedAlbum = manifest.albums.find(a => a.shared && a.owner === 'friend')!;

// Media is gitignored (regenerated by demo/fetch.ts), so the media tests use a temp dir with stand-ins.
const mediaDir = mkdtempSync(join(tmpdir(), 'demo-stub-'));
const VIDEO_BYTES = Buffer.from('0123456789abcdef');
mkdirSync(join(mediaDir, photo.id));
writeFileSync(join(mediaDir, photo.id, 'thumbnail.webp'), 'thumb');
writeFileSync(join(mediaDir, photo.id, 'thumbnail.jpg'), 'old jpeg');
// A media directory built before the WebP thumbnails: the friend's photo has only a JPEG one.
const OLD_THUMB = 'old-style thumb';
writeFileSync(join(mediaDir, photo.id, 'preview.jpg'), 'preview!');
mkdirSync(join(mediaDir, video.id));
writeFileSync(join(mediaDir, video.id, 'video.mp4'), VIDEO_BYTES);
mkdirSync(join(mediaDir, friends[0].id));
writeFileSync(join(mediaDir, friends[0].id, 'preview.jpg'), 'friend');
writeFileSync(join(mediaDir, friends[0].id, 'thumbnail.jpg'), OLD_THUMB);
afterAll(() => rmSync(mediaDir, {recursive: true, force: true}));

const stub = createStub({manifest, mediaDir});
const stubFetch = ((input: string | URL | Request, init?: RequestInit) => stub(new Request(input, init))) as typeof fetch;
const client = (apiKey = 'any-key-works') => new ImmichClient({baseUrl: 'http://stub:2283', apiKey, fetch: stubFetch, pollMs: 1, wakeTimeoutMs: 100});
const get = (path: string, headers: Record<string, string> = {'x-api-key': 'k'}) => stub(new Request('http://stub:2283' + path, {headers}));

describe('demo manifest', () => {
  it('holds only CC BY / BY-SA 4.0 items, each with attribution and a modification note', () => {
    expect(manifest.assets.length).toBeGreaterThan(900);
    const ids = new Set<string>();
    for (const a of manifest.assets) {
      expect(a.id).toMatch(UUID);
      expect(ids.has(a.id)).toBe(false);
      ids.add(a.id);
      expect(['CC BY 4.0', 'CC BY-SA 4.0']).toContain(a.license);
      expect(a.commonsUrl).toMatch(/^https:\/\/commons\.wikimedia\.org\/wiki\/File:/);
      expect(a.author).toBe('Kent Wang');
      expect(a.modifications.length).toBeGreaterThan(0);
      expect(a.thumbhash).toMatch(/^[A-Za-z0-9+/]+=*$/);
      expect(Number.isInteger(a.localOffsetHours * 4)).toBe(true);
    }
  });

  it('derives every clip from a photo in the dataset and licenses it like that photo', () => {
    const clips = manifest.assets.filter(a => a.kind === 'video');
    expect(clips.length).toBeGreaterThanOrEqual(10);
    expect(clips.length).toBeLessThanOrEqual(20);
    for (const c of clips) {
      const src = manifest.assets.find(a => a.id === c.sourceId)!;
      expect(src.kind).toBe('photo');
      expect(c.license).toBe(src.license);
      expect(c.durationMs).toBeGreaterThan(0);
      expect(c.modifications).toMatch(/derived/);
    }
  });

  it('has 3–5 own albums plus a shared one, one with missing GPS and one with video', () => {
    const own = manifest.albums.filter(a => a.owner === 'me');
    expect(own.length).toBeGreaterThanOrEqual(3);
    expect(own.length).toBeLessThanOrEqual(5);
    expect(sharedAlbum).toBeDefined();
    const members = manifest.albums.map(al => albumMembers(manifest, al));
    expect(members.every(m => m.length > 0)).toBe(true);
    expect(members.some(m => m.some(a => a.lat === null) && m.some(a => a.lat !== null))).toBe(true);
    expect(members.some(m => m.some(a => a.kind === 'video'))).toBe(true);
  });
});

describe('demo stub through the viewer adapter', () => {
  it('lists months whose counts add up to the key user\'s own assets', async () => {
    const months = await fetchManifestMonths(client());
    expect(months.reduce((n, m) => n + m.count, 0)).toBe(mine.length);
    expect(months.map(m => m.month)).toEqual([...months.map(m => m.month)].sort());
  });

  it('returns every own asset exactly once across the month buckets, with GPS and videos intact', async () => {
    const immich = client();
    const months = await fetchManifestMonths(immich);
    const cols = await Promise.all(months.map(m => fetchMonthColumns(immich, m.month)));
    cols.forEach((c, i) => expect(c.id.length).toBe(months[i].count));
    const ids = cols.flatMap(c => c.id);
    expect(ids.length).toBe(mine.length);
    expect(new Set(ids).size).toBe(mine.length);
    expect(friends.length).toBeGreaterThan(0);
    for (const f of friends) expect(ids).not.toContain(f.id);
    const byId = new Map(manifest.assets.map(a => [a.id, a]));
    let withGps = 0, videos = 0;
    for (const c of cols) for (let i = 0; i < c.id.length; i++) {
      const a = byId.get(c.id[i])!;
      expect(c.t[i]).toBe(Date.parse(a.takenAt));
      expect(c.off[i]).toBe(a.localOffsetHours);
      expect(c.lat[i]).toBe(a.lat);
      expect(c.lon[i]).toBe(a.lon);
      expect(c.thumbhash[i]).toBe(a.thumbhash);
      if (c.lat[i] !== null) withGps++;
      if (c.video[i]) { videos++; expect(c.dur[i]).toBe(a.durationMs); }
    }
    expect(withGps).toBe(mine.filter(a => a.lat !== null).length);
    expect(videos).toBe(mine.filter(a => a.kind === 'video').length);
  });

  it('buckets by local calendar month, like Immich', async () => {
    const [{timeBucket}] = await (await get('/api/timeline/buckets')).json() as {timeBucket: string}[];
    expect(timeBucket).toMatch(/^\d{4}-\d{2}-01T00:00:00\.000Z$/);
    const months = await fetchManifestMonths(client());
    for (const m of months.slice(0, 3)) {
      const c = await fetchMonthColumns(client(), m.month);
      for (let i = 0; i < c.id.length; i++) expect(new Date(c.t[i] + c.off[i] * 3600e3).toISOString().slice(0, 7)).toBe(m.month);
    }
  });

  it('leaves the coordinate columns out without withCoordinates=true', async () => {
    const month = (await fetchManifestMonths(client()))[0].month;
    const body = await (await get(`/api/timeline/bucket?timeBucket=${month}-01`)).json() as Record<string, unknown>;
    expect(body).not.toHaveProperty('latitude');
    expect(body).not.toHaveProperty('longitude');
    expect(Array.isArray(body.id)).toBe(true);
  });

  it('lists owned and shared albums with their date ranges', async () => {
    const albums = await fetchAlbums(client());
    expect(albums.map(a => a.id).sort()).toEqual(manifest.albums.map(a => a.id).sort());
    for (const a of albums) {
      const members = albumMembers(manifest, manifest.albums.find(m => m.id === a.id)!);
      expect(a.count).toBe(members.length);
      // Like Immich: local calendar days, midnight read as UTC.
      const days = members.map(m => Math.floor((Date.parse(m.takenAt) + m.localOffsetHours * 3600e3) / 86400e3) * 86400e3);
      expect(a.start).toBe(Math.min(...days));
      expect(a.end).toBe(Math.max(...days));
      expect(a.shared).toBe(a.id === sharedAlbum.id);
      // The cover is one of the album's photos, with GPS when it has any.
      const cover = members.find(m => m.id === a.cover);
      expect(cover?.kind).toBe('photo');
      expect(cover?.lat).not.toBeNull();
    }
  });

  it('models the shared album like Immich: owned by another user, listed only with shared=true', async () => {
    type Album = {id: string; ownerId: string; owner: {id: string}; shared: boolean; albumUsers: {user: {id: string}; role: string}[]};
    const owned = await (await get('/api/albums')).json() as Album[];
    const shared = await (await get('/api/albums?shared=true')).json() as Album[];
    expect(owned.map(a => a.id)).not.toContain(sharedAlbum.id);
    const dto = shared.find(a => a.id === sharedAlbum.id)!;
    expect(dto.shared).toBe(true);
    expect(dto.ownerId).toBe(dto.owner.id);
    expect(dto.ownerId).not.toBe(owned[0].ownerId);
    expect(dto.albumUsers.map(u => u.user.id)).toEqual([owned[0].ownerId]);
  });

  it('serves another user\'s assets through the shared album, with their owner id', async () => {
    const res = await fetchAlbumMembers(client(), sharedAlbum.id);
    for (const f of friends) expect(res.columns.id).toContain(f.id);
    expect(res.columns.id.some(id => mine.some(a => a.id === id))).toBe(true);
    const month = new Date(Date.parse(friends[0].takenAt) + friends[0].localOffsetHours * 3600e3).toISOString().slice(0, 7);
    const body = await (await get(`/api/timeline/bucket?timeBucket=${month}-01&albumId=${sharedAlbum.id}`)).json() as {id: string[]; ownerId: string[]};
    const owners = new Set(body.ownerId);
    expect(owners.size).toBe(2);
    const preview = await createApp(client()).request(`/api/assets/${friends[0].id}/thumbnail?size=preview`);
    expect(await preview.text()).toBe('friend');
  });

  it('returns album members through the album timeline buckets', async () => {
    for (const al of manifest.albums) {
      const res = await fetchAlbumMembers(client(), al.id);
      expect(res.columns.id.sort()).toEqual(albumMembers(manifest, al).map(a => a.id).sort());
      expect(res.version).toContain(`|${res.columns.id.length}|`);
    }
  });

  it('answers unknown albums and assets with 400 like Immich, which the adapter maps to not-found', async () => {
    const missing = '00000000-0000-4000-8000-000000000000';
    await expect(fetchAlbumMembers(client(), missing)).rejects.toMatchObject({status: 404, code: 'not-found'});
    expect((await get(`/api/assets/${missing}/thumbnail`)).status).toBe(400);
    expect((await get('/api/timeline/bucket')).status).toBe(400);
  });

  it('requires an API key (any value) except for ping and version', async () => {
    expect((await get('/api/timeline/buckets', {})).status).toBe(401);
    await expect(fetchManifestMonths(client(''))).rejects.toBeInstanceOf(HttpError);
    await expect(fetchManifestMonths(client(''))).rejects.toMatchObject({code: 'auth'});
    expect(await (await get('/api/server/ping', {})).json()).toEqual({res: 'pong'});
    expect(await (await get('/api/server/version', {})).json()).toEqual(STUB_VERSION);
  });
});

describe('demo stub media through the viewer relay', () => {
  const app = createApp(client());

  it('serves thumbnails and previews', async () => {
    const thumb = await app.request(`/api/assets/${photo.id}/thumbnail?size=thumbnail&c=${encodeURIComponent(photo.thumbhash)}`);
    expect(thumb.status).toBe(200);
    expect(thumb.headers.get('content-type')).toBe('image/webp'); // as Immich's own thumbnails
    expect(await thumb.text()).toBe('thumb');
    const old = await get(`/api/assets/${friends[0].id}/thumbnail`);
    expect(old.headers.get('content-type')).toBe('image/jpeg');
    expect(await old.text()).toBe(OLD_THUMB);
    const preview = await app.request(`/api/assets/${photo.id}/thumbnail?size=preview`);
    expect(await preview.text()).toBe('preview!');
    expect(preview.headers.get('content-length')).toBe('8');
    const head = await app.request(`/api/assets/${photo.id}/thumbnail?size=preview`, {method: 'HEAD'});
    expect(head.status).toBe(200);
  });

  it('plays video with byte ranges', async () => {
    const full = await app.request(`/api/assets/${video.id}/video`);
    expect(full.status).toBe(200);
    expect(full.headers.get('content-type')).toBe('video/mp4');
    expect(full.headers.get('accept-ranges')).toBe('bytes');
    const part = await app.request(`/api/assets/${video.id}/video`, {headers: {range: 'bytes=4-7'}});
    expect(part.status).toBe(206);
    expect(part.headers.get('content-range')).toBe(`bytes 4-7/${VIDEO_BYTES.length}`);
    expect(await part.text()).toBe('4567');
    const suffix = await get(`/api/assets/${video.id}/video/playback`, {'x-api-key': 'k', range: 'bytes=-3'});
    expect(await suffix.text()).toBe('def');
    expect((await get(`/api/assets/${video.id}/video/playback`, {'x-api-key': 'k', range: 'bytes=99-'})).status).toBe(404);
    const one = await get(`/api/assets/${video.id}/video/playback`, {'x-api-key': 'k', range: 'bytes=0-0'});
    expect(one.status).toBe(206);
    expect(one.headers.get('content-length')).toBe('1');
    expect(await one.text()).toBe('0');
    const tail = await get(`/api/assets/${video.id}/video/playback`, {'x-api-key': 'k', range: 'bytes=15-'});
    expect(await tail.text()).toBe('f');
    // 16 digits: not a range the stub honours, so the whole file comes back.
    const absurd = await get(`/api/assets/${video.id}/video/playback`, {'x-api-key': 'k', range: 'bytes=0-9999999999999999'});
    expect(absurd.status).toBe(200);
    expect(Buffer.from(await absurd.arrayBuffer()).equals(VIDEO_BYTES)).toBe(true);
  });

  it('has no video for a photo and nothing for unknown ids', async () => {
    expect((await app.request(`/api/assets/${photo.id}/video`)).status).toBe(404);
    expect((await app.request(`/api/assets/00000000-0000-4000-8000-000000000000/thumbnail`)).status).toBe(404);
  });
});
